// wgodot-changes::file
#include "wgodot_cpp_emitter.h"
#include "wgodot_cpp_names.h"

int64_t WGodotCppEmitter::preload_id(const Resource *p_resource) {
	const String path = p_resource->get_path();
	unit_preloads.insert(path);
	if (preload_indices.has(path)) {
		return resource_id(path);
	}
	if (prepared_resource_ids) {
		diagnostics.push_back("Preload was not prepared before parallel resource generation: " + path);
		return -1;
	}
	int index = preloads.size();
	preloads.push_back({ path, p_resource->get_class(), false });
	preload_indices.insert(path, index);
	return resource_id(path);
}

void WGodotCppEmitter::collect_preload_ids(const Variant &p_value, HashSet<int64_t> &r_ids) {
	if (p_value.get_type() == Variant::OBJECT) {
		const Resource *resource = Object::cast_to<Resource>(static_cast<Object *>(p_value));
		if (resource && !Object::cast_to<Script>(resource)) {
			r_ids.insert(preload_id(resource));
		}
	} else if (p_value.get_type() == Variant::ARRAY) {
		const Array values = p_value;
		for (const Variant &value : values) {
			collect_preload_ids(value, r_ids);
		}
	} else if (p_value.get_type() == Variant::DICTIONARY) {
		const Dictionary values = p_value;
		for (const KeyValue<Variant, Variant> &entry : values) {
			collect_preload_ids(entry.key, r_ids);
			collect_preload_ids(entry.value, r_ids);
		}
	}
}

void WGodotCppEmitter::emit_preloads() {
	String source = "// wgodot-changes::file\n// Generated by WGodot. DO NOT EDIT MANUALLY.\n#include \"modules/wgodot/wgodot_preloads.h\"\n\n";
	if (!preloads.is_empty()) {
		source += "static const WGodotPreloads::Definition preloads[] = {\n";
		Vector<String> paths;
		for (const auto &preload : preloads) {
			paths.push_back(preload.path);
		}
		paths.sort();
		for (const String &path : paths) {
			const auto &preload = preloads[preload_indices[path]];
			source += "\t{" + itos(resource_id(preload.path)) + ", " + WGodotCppNames::quoted(preload.type) + ", " + (preload.asynchronous ? "true" : "false") + "},\n";
		}
		source += "};\n\n";
	}
	source += "void register_main_game_preloads() {\n\tWGodotPreloads::set_manifest(" + String(preloads.is_empty() ? "nullptr" : "preloads") + ", " + itos(preloads.size()) + ");\n}\n";
	store_file("game_preloads.cpp", source);
}
