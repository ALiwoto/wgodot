// wgodot-changes::file
#include "wgodot_cpp_emitter.h"
#include "wgodot_cpp_names.h"
#include "wgodot_resource_schema.h"
#include "wgodot_resource_types.h"

#include "core/object/class_db.h"

using namespace WGodotCppNames;

void WGodotCppEmitter::emit_resource_codecs() {
	String declarations = "// Generated by WGodot. DO NOT EDIT.\n#include \"modules/wgodot/codecs/resource_protobuf.h\"\nnamespace WGodotGame {\n";
	String registrations;
	int count = 0;
	HashSet<uint64_t> identities;
	WGodotResourceTypes types;
	for (const auto &game : project.get_classes()) {
		types.add_class(game.node);
	}
	for (const auto &game : project.get_classes()) {
		if (game.node->is_abstract || game.node->wgodot_is_interface || !ClassDB::is_parent_class(native_base(game.node->self_type), SNAME("Resource"))) {
			continue;
		}
		const WGodotResourceSchema schema(game.node);
		if (schema.fields.is_empty()) {
			continue;
		}
		String error;
		const StringName name = game.node->get_global_name().is_empty() ? StringName(game.node->fqcn) : game.node->get_global_name();
		if (types.check_exports(name, error) != OK) {
			diagnostics.push_back(game.script_path + ": " + error);
			return;
		}
		if (!schema.id || identities.has(schema.id)) {
			diagnostics.push_back("Resource class identity collision: " + game.node->fqcn);
			return;
		}
		identities.insert(schema.id);
		current_class = &game;
		function_failed = false;
		class_dependencies.clear();
		class_native_headers.clear();
		String fields;
		for (int i = 0; i < schema.fields.size(); i++) {
			const auto *variable = schema.fields[i];
			const String field_type = type(variable->type_constraint, variable);
			if (field_type == "Variant" || variable->type_constraint.is_variant()) {
				diagnostics.push_back(game.script_path + ": exported resource field requires a concrete type: " + String(variable->identifier->name));
				return;
			}
			const String accessor = symbol(variable->identifier->name);
			const auto &datatype = variable->type_constraint;
			const bool direct_container = variable->property == GDScriptParser::VariableNode::PROP_NONE && (is_warray(datatype) || is_wdictionary(datatype) || is_packed(datatype));
			const String initialize = direct_container ? ", &" + game.cpp_name + "::v_" + accessor : String();
			fields += "\t\tBinding<" + game.cpp_name + ", " + field_type + ", &" + game.cpp_name + "::read_" + accessor + ", &" + game.cpp_name + "::write_" + accessor + initialize + ">::field_info(" + itos(i + 1) + "),\n";
		}
		String source = source_header(game.script_path, game.cpp_name);
		source += "#include \"modules/wgodot/native/wgodot_native_resource_protobuf.h\"\n#include " + quoted(game.cpp_name + ".h") + "\n";
		Vector<String> includes;
		for (const auto &dependency : class_dependencies) {
			if (dependency != game.cpp_name) {
				includes.push_back(dependency + ".h");
			}
		}
		for (const auto &header : class_native_headers) {
			includes.push_back(header);
		}
		includes.sort();
		for (const auto &header : includes) {
			source += "#include " + quoted(header) + "\n";
		}
		const String function = "resource_codec_" + uitos(schema.id);
		source += "namespace WGodotGame {\nconst WGodotResourceProtobuf::Codec *" + function + "() {\n\tusing namespace WGodotResourceProtobuf;\n\tstatic const Field fields[] = {\n" + fields + "\t};\n\tstatic const Codec codec { " + uitos(schema.id) + "ULL, " + uitos(schema.fingerprint) + "ULL, " + quoted(game.cpp_name) + ", []() -> Ref<Resource> { return memnew(" + game.cpp_name + "); }, fields, " + itos(schema.fields.size()) + " };\n\treturn &codec;\n}\n}\n";
		store_file(game.cpp_name + ".resource.cpp", source);
		declarations += "const WGodotResourceProtobuf::Codec *" + function + "();\n";
		registrations += "\t\tWGodotGame::" + function + "(),\n";
		count++;
	}
	declarations += "}\nvoid register_main_game_resource_codecs() {\n";
	if (count) {
		declarations += "\tstatic const WGodotResourceProtobuf::Codec *const codecs[] = {\n" + registrations + "\t};\n\tWGodotResourceProtobuf::initialize(codecs, " + itos(count) + ");\n";
	}
	declarations += "}\n";
	store_file("game_resource_codecs.cpp", declarations);
	current_class = nullptr;
}
